"""Owned default selector and derived ACL copy; native sources remain untouched."""
from pathlib import Path
import re
import tempfile

from .atomic import write
from .errors import Conflict,EngineError
from .mail_adapter import bounded,sha,trusted
from .native_acl import MARKER,render

DEFAULT=Path('/etc/exim4/exim4.conf')
RUNTIME=Path('/run/clamshield-exim')
BASE=RUNTIME/'native.conf'
SOURCE=RUNTIME/'native-source.conf'
POLICY=RUNTIME/'policy.conf'
HOOK=RUNTIME/'hook.conf'
STOCK=Path('/var/lib/exim4/config.autogenerated')
LOADED='CLAMSHIELD_NATIVE_CONFIG_INCLUDED'


def selector_text():
    # Exim supports macro conditionals, not file-existence conditionals. Each
    # complete derived config declares LOADED; the first present copy wins.
    return ('# Managed by clamshield: native configuration selector\n'
            '.include_if_exists '+str(POLICY)+'\n.ifndef '+LOADED+'\n'
            '.include_if_exists '+str(BASE)+'\n.ifndef '+LOADED+'\n'
            '.include '+str(STOCK)+'\n.endif\n.endif\n')


def verify_selector(*,allow_absent=False):
    if not DEFAULT.exists() and not DEFAULT.is_symlink():
        if allow_absent:return False
        raise Conflict('Owned native configuration selector is missing')
    trusted(DEFAULT)
    if DEFAULT.read_text()!=selector_text():
        raise Conflict('Existing native default configuration is not replaced; review is required')
    return True


def verify_unit(guard):
    """Do not replace an unknown vendor/admin reload operation by guessing.

    StartPre stays additive. Reload is the supported native generator followed
    by HUP, with explicit owned output because an explicit default config makes
    the distro generator's ordinary default-output invocation a no-op.
    """
    raw=bounded(['/usr/bin/systemctl','cat','exim4.service'],timeout=5).stdout.decode()
    sections=re.split(r'^# (/[^\n]+)\n',raw,flags=re.M)
    if len(sections)<3:raise EngineError('Native Exim unit layout is unavailable')
    vendor_seen=False
    for index in range(1,len(sections),2):
        name,text=sections[index],sections[index+1]
        lines=re.sub(r'\\\n[ \t]*',' ',text).splitlines()
        reloads=[re.sub(r'^ExecReload\s*=\s*','ExecReload=',' '.join(line.split()))
                 for line in lines if re.match(r'^\s*ExecReload\s*=',line)]
        if name==str(guard):continue
        if name in ('/usr/lib/systemd/system/exim4.service','/lib/systemd/system/exim4.service'):
            vendor_seen=True
            if reloads!=['ExecReload=/usr/sbin/update-exim4.conf $UPEX4OPTS ; kill -HUP $MAINPID']:
                raise Conflict('Native Exim reload operation changed; review is required')
        elif reloads:
            raise Conflict('Administrator Exim reload operations are preserved; integration requires review')
    if not vendor_seen:raise Conflict('Native Exim unit is not a supported package unit')


def clear_policy():
    if not POLICY.exists() and not POLICY.is_symlink():return
    trusted(POLICY)
    if not POLICY.read_text().startswith(MARKER):raise Conflict('Foreign runtime ACL configuration retained')
    POLICY.unlink()


def prepare():
    verify_selector();trusted(RUNTIME,directory=True)
    native=SOURCE if SOURCE.exists() or SOURCE.is_symlink() else BASE
    trusted(native)
    if native.stat().st_size>8*1024**2:raise EngineError('Generated native configuration exceeds its limit')
    before=sha(native);source=native.read_text()
    if source.splitlines().count(LOADED+'=1')!=1:
        raise EngineError('Generated native configuration has no unique selector marker')
    include='.include_if_exists '+str(HOOK)+'\n'
    if source.count(include)!=1:raise EngineError('Generated native configuration has no unique owned hook')
    # Publish policy and the verified adapter binding in one atomic file. A
    # timed-out helper cannot leave delegated ACLs with no local_scan adapter.
    content=render(source.replace(include,'local_scan_path = /opt/clamshield-mail/local_scan.so\n'))
    # Never expose an unparsed candidate to ordinary Exim processes.
    with tempfile.TemporaryDirectory(prefix='.policy-check-',dir=RUNTIME) as folder:
        candidate=Path(folder)/'candidate.conf';write(candidate,content,0o600)
        bounded(['/usr/sbin/exim4','-C',str(candidate),'-bV'],timeout=5)
        if sha(native)!=before:raise Conflict('Native configuration changed during ACL preparation')
        verify_selector();write(POLICY,content,0o644)
    return {'native_sha256':before,'policy_sha256':sha(POLICY)}

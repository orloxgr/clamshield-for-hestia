from pathlib import Path
import tempfile
import unittest
from unittest.mock import Mock,patch

from clamshield.errors import Conflict
from clamshield.native_acl_runtime import verify_unit,verify_selector,selector_text

GUARD=Path('/etc/systemd/system/exim4.service.d/clamshield-mail.conf')
VENDOR='''# /usr/lib/systemd/system/exim4.service
[Service]
ExecStartPre=/usr/sbin/update-exim4.conf $UPEX4OPTS
ExecReload=/usr/sbin/update-exim4.conf $UPEX4OPTS ; \\
\tkill -HUP $MAINPID
'''


class NativeAclRuntimeTests(unittest.TestCase):
    def test_known_vendor_reload_and_own_override_are_supported(self):
        text=VENDOR+'\n# '+str(GUARD)+'\nExecReload=\nExecReload=kill -HUP $MAINPID\n'
        with patch('clamshield.native_acl_runtime.bounded',return_value=Mock(stdout=text.encode())):
            verify_unit(GUARD)

    def test_unknown_vendor_or_administrator_reload_is_not_overridden(self):
        for text in (VENDOR.replace('kill -HUP','kill -USR1'),
                     VENDOR+'\n# /etc/systemd/system/exim4.service.d/admin.conf\nExecReload=/usr/local/bin/custom\n',
                     VENDOR+'\n# /etc/systemd/system/exim4.service.d/admin.conf\n ExecReload = /usr/local/bin/custom\n',
                     VENDOR.replace('/usr/lib/systemd/system/exim4.service','/etc/systemd/system/exim4.service')):
            with self.subTest(text=text),patch('clamshield.native_acl_runtime.bounded',return_value=Mock(stdout=text.encode())),self.assertRaises(Conflict):
                verify_unit(GUARD)

    def test_selector_has_independent_native_and_offline_fallbacks(self):
        text=selector_text()
        self.assertIn('.include_if_exists /run/clamshield-exim/policy.conf',text)
        self.assertIn('.include_if_exists /run/clamshield-exim/native.conf',text)
        self.assertIn('.include /var/lib/exim4/config.autogenerated',text)
        self.assertEqual(2,text.count('.ifndef CLAMSHIELD_NATIVE_CONFIG_INCLUDED'))

    def test_foreign_or_edited_native_default_is_never_adopted(self):
        with tempfile.TemporaryDirectory() as folder:
            target=Path(folder)/'exim4.conf'
            with patch('clamshield.native_acl_runtime.DEFAULT',target):
                self.assertFalse(verify_selector(allow_absent=True))
                target.write_text('administrator native config\n')
                with self.assertRaises(Conflict):verify_selector(allow_absent=True)
                self.assertEqual('administrator native config\n',target.read_text())
